TextMetrics ESP32Canvas::measure_text(const char* text) {
    /* Find the best matching atlas size (bold or regular) */
    int target = (int)(_state.font_size + 0.5f);
    const FontAtlas* atlas = font_atlas_find_styled(_state.font_commp, _state.font_bold, target);
    if (!atlas) {
        /* Fallback to bitmap measurement */
        int len = 0; while (text[len]) len++;
        float scale = _state.font_size / (float)kFontH;
        float w = len * kFontW * scale;
        float h = kFontH * scale;
        return TextMetrics{w, h, h * 0.8f, h * 0.2f};
    }

    float scale = _state.font_size / (float)atlas->size;
    float width = 0;
    for (int i = 0; text[i]; i++) {
        int ch = (unsigned char)text[i];
        const FontGlyph* g = font_atlas_glyph(atlas, ch);
        if (g) {
            width += g->advance * scale;
        } else {
            width += atlas->size * 0.5f * scale; /* fallback width */
        }
    }
    float height = atlas->line_height * scale;
    float ascent = atlas->ascent * scale;
    float descent = atlas->descent * scale;
    return TextMetrics{width, height, ascent, descent};
}

void ESP32Canvas::draw_text(const char* text, float x, float y, const char* align) {
    if (!text || !text[0]) return;

    int target = (int)(_state.font_size + 0.5f);
    const FontAtlas* atlas = font_atlas_find_styled(_state.font_commp, _state.font_bold, target);

    if (!atlas) {
        /* Fall back to bitmap font — see below */
        goto bitmap_fallback;
    }

    {
        float scale = _state.font_size / (float)atlas->size;
        TextMetrics m = measure_text(text);

        float draw_x = x;
        if (align[0] == 'c') draw_x = x - m.width / 2.0f;
        else if (align[0] == 'r') draw_x = x - m.width;

        float draw_y = y - m.ascent;

        uint8_t fr = _state.fill_r, fg = _state.fill_g, fb = _state.fill_b, fa = _state.fill_a;

        for (int ci = 0; text[ci]; ci++) {
            int ch = (unsigned char)text[ci];
            const FontGlyph* glyph = font_atlas_glyph(atlas, ch);
            if (!glyph) {
                draw_x += atlas->size * 0.5f * scale;
                continue;
            }
            if (!glyph->bitmap) {
                /* Bitmap-less glyph (space): honor its REAL advance —
                 * the old 0.5*size fallback double-spaced text and
                 * diverged from measure_text (found by the M5 config
                 * crosscheck). */
                draw_x += glyph->advance * scale;
                continue;
            }

            int glyph_w = glyph->width;
            int glyph_h = glyph->height;
            float gx = draw_x + glyph->bearing_x * scale;
            float gy = draw_y + (atlas->ascent - glyph->bearing_y) * scale;

            /* Render glyph bitmap with scaling */
            int sw = (int)(glyph_w * scale + 0.5f);
            int sh = (int)(glyph_h * scale + 0.5f);
            int igx = (int)(gx + 0.5f);
            int igy = (int)(gy + 0.5f);

            for (int py = 0; py < sh; py++) {
                int src_row = py * glyph_h / sh;
                int screen_y = igy + py;
                if (!in_band(screen_y)) continue;

                for (int px = 0; px < sw; px++) {
                    int src_col = px * glyph_w / sw;
                    uint8_t alpha = glyph->bitmap[src_row * glyph_w + src_col];
                    if (alpha == 0) continue;

                    /* Modulate glyph alpha with fill alpha */
                    uint8_t final_a = (uint8_t)((alpha * fa + 127) / 255);
                    put_pixel(igx + px, screen_y, fr, fg, fb, final_a);
                }
            }

            draw_x += glyph->advance * scale;
        }
        return;
    }

bitmap_fallback:
    /* 8x16 bitmap font rendering */
    {
        float scale = _state.font_size / (float)kFontH;
        TextMetrics m = measure_text(text);

        float draw_x = x;
        if (align[0] == 'c') draw_x = x - m.width / 2.0f;
        else if (align[0] == 'r') draw_x = x - m.width;

        float draw_y = y - m.ascent;

        uint8_t r = _state.fill_r, g = _state.fill_g, b = _state.fill_b, a = _state.fill_a;

        for (int ci = 0; text[ci]; ci++) {
            int ch = (unsigned char)text[ci];
            if (ch < kFontFirstChar || ch > kFontLastChar) ch = '?';
            int idx = ch - kFontFirstChar;

            const uint8_t* glyph = font_8x16[idx];
            float gx = draw_x + ci * kFontW * scale;

            int sw = (int)(kFontW * scale + 0.5f);
            int sh = (int)(kFontH * scale + 0.5f);
            int igx = (int)(gx + 0.5f);
            int igy = (int)(draw_y + 0.5f);

            for (int py = 0; py < sh; py++) {
                int src_row = py * kFontH / sh;
                int screen_y = igy + py;
                if (!in_band(screen_y)) continue;

                uint8_t bits = glyph[src_row];
                if (bits == 0) continue;
                for (int px = 0; px < sw; px++) {
                    int src_col = px * kFontW / sw;
                    if (bits & (0x80 >> src_col)) {
                        put_pixel(igx + px, screen_y, r, g, b, a);
                    }
                }
            }
        }
    }
}

