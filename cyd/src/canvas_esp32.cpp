/* -------------------------------------------------------------------
 * Image pipeline — decode_image / draw_image / free_image (M5)
 *
 * Supported codecs on this tier (no-PSRAM heap budget):
 *   - BMP 24-bit BI_RGB (top-down or bottom-up)      -> RGB565
 *   - BMP 32-bit (BGRA)                              -> RGB565 + A8
 *   - CI16 raw sprite  ("CI16" u16 w u16 h, RGB565le) -> RGB565
 * PNG/JPEG are NOT decoded on-device (deferred; the offline bakers
 * emit BMP/CI16 for embedded targets).  Oversized images are refused.
 * ------------------------------------------------------------------- */

static constexpr size_t kMaxDecodedBytes = 120 * 1024;

static inline uint32_t rd_le32(const uint8_t* p) {
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}
static inline uint16_t rd_le16(const uint8_t* p) {
    return (uint16_t)p[0] | ((uint16_t)p[1] << 8);
}
static inline uint16_t pack565(uint8_t r, uint8_t g, uint8_t b) {
    return (uint16_t)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

ImageHandle ESP32Canvas::decode_image(const uint8_t* data, size_t len) {
    if (!data || len < 8) return nullptr;

    /* ---- CI16 raw sprite ---- */
    if (data[0] == 'C' && data[1] == 'I' && data[2] == '1' && data[3] == '6') {
        uint16_t w = rd_le16(data + 4);
        uint16_t h = rd_le16(data + 6);
        size_t need = (size_t)w * h * 2;
        if (w == 0 || h == 0 || len < 8 + need) return nullptr;
        if (need > kMaxDecodedBytes) {
            ESP_LOGW(TAG, "decode_image: CI16 %ux%u exceeds budget", w, h);
            return nullptr;
        }
        auto* img = static_cast<DecodedImage*>(malloc(sizeof(DecodedImage)));
        if (!img) return nullptr;
        img->w = w; img->h = h; img->alpha = nullptr;
        img->pix565 = static_cast<uint16_t*>(malloc(need));
        if (!img->pix565) { free(img); return nullptr; }
        const uint8_t* src = data + 8;
        for (size_t i = 0; i < (size_t)w * h; i++) {
            img->pix565[i] = rd_le16(src + i * 2);
        }
        return img;
    }

    /* ---- BMP ---- */
    if (data[0] == 'B' && data[1] == 'M' && len >= 54) {
        uint32_t px_off = rd_le32(data + 10);
        uint32_t dib = rd_le32(data + 14);
        if (dib < 40) return nullptr;
        int32_t w = (int32_t)rd_le32(data + 18);
        int32_t h_signed = (int32_t)rd_le32(data + 22);
        uint16_t bpp = rd_le16(data + 28);
        uint32_t compression = rd_le32(data + 30);
        bool top_down = h_signed < 0;
        int32_t h = top_down ? -h_signed : h_signed;

        if (w <= 0 || h <= 0 || w > 4096 || h > 4096) return nullptr;
        if (bpp != 24 && bpp != 32) return nullptr;
        if (compression != 0 && compression != 3 /* BITFIELDS, assume BGRA */)
            return nullptr;

        size_t bytes_pp = bpp / 8;
        size_t stride = ((size_t)w * bytes_pp + 3) & ~3u;
        if (px_off + stride * h > len) return nullptr;

        size_t need = (size_t)w * h * 2 + (bpp == 32 ? (size_t)w * h : 0);
        if (need > kMaxDecodedBytes) {
            ESP_LOGW(TAG, "decode_image: BMP %ldx%ld exceeds budget",
                     (long)w, (long)h);
            return nullptr;
        }

        auto* img = static_cast<DecodedImage*>(malloc(sizeof(DecodedImage)));
        if (!img) return nullptr;
        img->w = (uint16_t)w; img->h = (uint16_t)h;
        img->pix565 = static_cast<uint16_t*>(malloc((size_t)w * h * 2));
        img->alpha = (bpp == 32)
            ? static_cast<uint8_t*>(malloc((size_t)w * h)) : nullptr;
        if (!img->pix565 || (bpp == 32 && !img->alpha)) {
            free(img->pix565); free(img->alpha); free(img);
            return nullptr;
        }

        for (int32_t row = 0; row < h; row++) {
            int32_t src_row = top_down ? row : (h - 1 - row);
            const uint8_t* src = data + px_off + (size_t)src_row * stride;
            for (int32_t col = 0; col < w; col++) {
                const uint8_t* p = src + (size_t)col * bytes_pp;
                uint8_t b = p[0], g = p[1], r = p[2];
                size_t idx = (size_t)row * w + col;
                img->pix565[idx] = pack565(r, g, b);
                if (img->alpha) img->alpha[idx] = p[3];
            }
        }
        return img;
    }

    return nullptr;   /* undecodable — caller renders fallback */
}

void ESP32Canvas::draw_image(ImageHandle handle, float x, float y,
                             float w, float h) {
    auto* img = static_cast<DecodedImage*>(handle);
    if (!img || !img->pix565 || w <= 0 || h <= 0) return;

    int dx0 = (int)floorf(x);
    int dy0 = (int)floorf(y);
    int dx1 = (int)ceilf(x + w) - 1;
    int dy1 = (int)ceilf(y + h) - 1;

    /* Early band rejection */
    if (dy1 < _row_lo || dy0 > _row_hi) return;

    for (int row = dy0; row <= dy1; row++) {
        if (!in_band(row)) continue;
        /* Nearest-neighbor source row */
        int sy = (int)(((float)row + 0.5f - y) * img->h / h);
        if (sy < 0) sy = 0;
        if (sy >= img->h) sy = img->h - 1;
        const uint16_t* src_row = img->pix565 + (size_t)sy * img->w;
        const uint8_t* alpha_row =
            img->alpha ? img->alpha + (size_t)sy * img->w : nullptr;

        for (int col = dx0; col <= dx1; col++) {
            int sx = (int)(((float)col + 0.5f - x) * img->w / w);
            if (sx < 0) sx = 0;
            if (sx >= img->w) sx = img->w - 1;

            uint16_t c = src_row[sx];
            uint8_t a = alpha_row ? alpha_row[sx] : 255;
            if (a == 0) continue;

            uint8_t r = (c >> 8) & 0xF8; r |= r >> 5;
            uint8_t g = (c >> 3) & 0xFC; g |= g >> 6;
            uint8_t b = (c << 3) & 0xF8; b |= b >> 5;
            put_pixel(col, row, r, g, b, a);
        }
    }
}

void ESP32Canvas::free_image(ImageHandle handle) {
    auto* img = static_cast<DecodedImage*>(handle);
    if (!img) return;
    free(img->pix565);
    free(img->alpha);
    free(img);
}
