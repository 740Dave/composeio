void ESP32Canvas::set_opacity(float a) {
    /* Real since M5: global alpha multiplier applied to every pixel
     * write (put_pixel), saved/restored with the graphics state. */
    if (a < 0.0f) a = 0.0f;
    if (a > 1.0f) a = 1.0f;
    _state.opacity = a;
}

/* -------------------------------------------------------------------
 * Save / Restore
 * ------------------------------------------------------------------- */

void ESP32Canvas::save() {
    if (_state_depth < kMaxStateDepth) {
        _state_stack[_state_depth] = _state;
        _state_depth++;
    }
}

void ESP32Canvas::restore() {
    if (_state_depth > 0) {
        _state_depth--;
        _state = _state_stack[_state_depth];
    }
}

/* Transform ops — contract stubs ([CXC-R-DRAW] 2026-07-06, the
 * [SPEC:CXC-BIND] bindable-transform pass).  A raster transform inside
 * the 16-scanline band renderer is M5+ work (rotate requires either a
 * full-frame scratch surface or per-band inverse-mapping); until then
 * these are documented no-ops and transform-bound widgets draw
 * untransformed on this tier.  Kept virtual-complete so the C++
 * contract stays in lockstep with the Python ABC. */

void ESP32Canvas::translate(float /*dx*/, float /*dy*/) {}
void ESP32Canvas::rotate(float /*angle*/) {}
void ESP32Canvas::scale(float /*sx*/, float /*sy*/) {}

void ESP32Canvas::clip_rect(float x, float y, float w, float h) {
    if (_state.has_clip) {
        float cx1 = std::max(x, _state.clip_x);
        float cy1 = std::max(y, _state.clip_y);
        float cx2 = std::min(x + w, _state.clip_x + _state.clip_w);
        float cy2 = std::min(y + h, _state.clip_y + _state.clip_h);
        _state.clip_x = cx1;
        _state.clip_y = cy1;
        _state.clip_w = (cx2 > cx1) ? cx2 - cx1 : 0;
        _state.clip_h = (cy2 > cy1) ? cy2 - cy1 : 0;
    } else {
        _state.clip_x = x;
        _state.clip_y = y;
        _state.clip_w = w;
        _state.clip_h = h;
        _state.has_clip = true;
    }
    _state.clip_radius = 0.0f;   /* a plain clip is rectangular */
}

void ESP32Canvas::clip_round_rect(float x, float y, float w, float h,
                                  float radius) {
    /* Axis-aligned bounds first (intersects any existing clip); then the
     * corner radius, clamped to half the smaller extent.  Nested rounded
     * clips are not composited (the arc applies to THIS rect) — the only
     * use-site (the gauge bar fill) clips a fresh save()d state. */
    clip_rect(x, y, w, h);
    float maxr = std::min(_state.clip_w, _state.clip_h) * 0.5f;
    if (radius < 0.0f) radius = 0.0f;
    if (radius > maxr) radius = maxr;
    _state.clip_radius = radius;
}

/* -------------------------------------------------------------------
 * Text rendering
 *
 * If a generated font atlas is available (font_atlas.h), use it for
 * antialiased proportional text. Otherwise fall back to the 8x16 bitmap.
 * ------------------------------------------------------------------- */

/* Case-insensitive family match: "commp" / "common pixel" -> the COMMP
 * pixel family; anything else -> the default sans-serif family.  Local
 * (not the atlas header's helper) so set_font works in the no-atlas
 * fallback build too. */
static bool family_is_commp(const char* family) {
    if (!family) return false;
    auto lc = [](char c) -> char {
        return (c >= 'A' && c <= 'Z') ? (char)(c - 'A' + 'a') : c; };
    auto ieq = [&](const char* s, const char* t) -> bool {
        while (*s && *t) { if (lc(*s) != lc(*t)) return false; s++; t++; }
        return *s == *t; };
    return ieq(family, "commp") || ieq(family, "common pixel");
}

void ESP32Canvas::set_font(const char* family, float size, const char* weight) {
    _state.font_size = size;
    _state.font_bold = (weight && weight[0] == 'b');
    _state.font_commp = family_is_commp(family);
}

