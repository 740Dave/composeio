"""Shared test data for the compose_plugins first wave.

``valid_manifest()`` is a TEST MANIFEST shaped like hello-world v1
([CXC-PC-HELLO-V1]): both hosts, issue_tracker and codeowners present, one
publish STATE, one publish EVENT, one subscribe EVENT. It is data for the
validator, NOT the hello-world plug-in (which is not built in this wave): its
``config_schema`` is a hand-written literal, not one generated by
``compose-plugin build``.
"""
from __future__ import annotations

import copy

import pytest

from compose_plugins.errors import Refusal

_VALID = {
    "contract": "0.1",
    "domain": "hello_world",
    "name": "Hello World",
    "version": "1.0.0",
    "description": "Greets on the bus and answers pings with pongs.",
    "documentation": "https://example.invalid/hello_world",
    "issue_tracker": "https://example.invalid/hello_world/issues",
    "codeowners": ["@example-user", "@example-org/plugins-team"],
    "requirements": [],
    "run": {"form": "python", "entry": "hello_world.plugin:HelloWorld"},
    "isolation_floor": "inprocess",
    "config_schema": {
        "properties": {"greeting": {"default": "hello", "title": "Greeting",
                                    "type": "string"}},
        "title": "Config", "type": "object",
    },
    "bus": {
        "publishes": [
            {"namespace": "plugins/hello_world/greeting", "type": "STATE"},
            {"namespace": "plugins/hello_world/pong", "type": "EVENT"},
        ],
        "subscribes": [
            {"namespace": "plugins/hello_world/ping", "type": "EVENT"},
        ],
    },
    "hosts": {"composeio": {}, "gnomon": {}},
}


def valid_manifest() -> dict:
    return copy.deepcopy(_VALID)


def empty_section(section) -> "list[Refusal]":
    """A test host's section validator: its own section must be ``{}``."""
    if section != {}:
        return [Refusal("", f"{section!r} — this test host's section holds nothing in v0.1")]
    return []


@pytest.fixture
def manifest() -> dict:
    return valid_manifest()


@pytest.fixture(autouse=True)
def _release_plugin_managers():
    """Release every PluginManager a test made (its in-process modules too)."""
    yield
    import wave2_helpers
    while wave2_helpers.MADE:
        wave2_helpers.MADE.pop().close()
