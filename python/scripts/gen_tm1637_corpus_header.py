#!/usr/bin/env python3
"""
gen_tm1637_corpus_header.py — TM1637 backend PARITY corpus.  PLAN I3.
[SPEC:CXC-VISION] [CXC-VISION-SEMANTIC-REALIZATION] [CXC-VISION-EPISTEMICS]

WHY A PARITY CORPUS AND NOT A C++ ROUND TRIP.  The same argument as
gen_uart_frame_corpus_header.py: a C++ test that encodes a glyph and then
decodes it passes with a fully PERMUTED segment table, because both halves
make the same mistake.  A seven-segment display is the worst case of that
class — a wrong table produces CONFIDENT, WELL-FORMED, WRONG glyphs, and
the only observer able to notice is a human looking at the tube.

THE ORACLE IS THE RASTER WIDGET, python/composeio/render/widgets/
seven_segment.py, which is the realization that already runs and has been
looked at on glass.  Pinning the firmware to it is what makes
[CXC-VISION-SEMANTIC-REALIZATION] checkable rather than aspirational: the
claim is that ONE semantic value reads the SAME on a 480x320 panel and on
a 4-digit tube, and this corpus is the instrument for that claim.

WHAT IT PINS, in two independent layers that must not be fused:

  1. SEMANTICS — character -> the lit subset of {a..g}.  Oracle:
     seven_segment.lit_segments().  Shared across every realization.
  2. JUSTIFICATION — value + digit count -> the displayed cell string.
     Oracle: SevenSegmentDisplay._display_value().  Also shared.

WHAT IT CANNOT PIN, and the header says so where a reader will trip over
it: the SEGMENT MAP (which SEG pin drives which physical bar) is a
property of the breakout PCB's traces.  No Python oracle knows it, no
machine signal on the wire reveals it, and it needs eyes on a lit tube.
The corpus deliberately carries the LETTER sets so a wrong map is a
one-line fix in the map and not a regeneration of this file.

REGENERATE after any change to the truth table or the justification rule:
    python3 python/scripts/gen_tm1637_corpus_header.py
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "python"))
sys.path.insert(0, REPO)

from composeio.render.widgets.seven_segment import (  # noqa: E402
    SEGMENT_ORDER,
    SevenSegmentDisplay,
    lit_segments,
)

OUT = os.path.join(REPO, "cyd", "test", "tm1637_corpus_generated.h")

#: Characters the C++ side can address with a char literal.  '°' is in the
#: Python table but is multi-byte UTF-8; the firmware reaches it through
#: the ASCII placeholder '~', and THAT SUBSTITUTION IS PINNED HERE so the
#: omission cannot become silent.
CHAR_CASES = list("0123456789abcdefABCDEF-_ ") + ["~"]
PLACEHOLDER = {"~": "°"}

#: Values x digit counts.  Chosen to exercise the three regimes that the
#: justification rule distinguishes — shorter than the surface (pads),
#: exactly the surface, longer than the surface (truncates from the LEFT).
#: A corpus of only exact-fit cases cannot tell right-justification from
#: left-justification, which is the shape of self-confirming evidence this
#: repo keeps paying for.
JUSTIFY_CASES = [
    ("", 4), ("7", 4), ("42", 4), ("123", 4), ("1234", 4),
    ("12345", 4), ("123456", 4),
    ("-1", 4), ("-42", 4), ("-1234", 4),
    ("8", 1), ("88", 1), ("1234", 6), ("123456", 6), ("1234567", 6),
    ("0", 4), ("00", 4),
]


def c_escape(ch: str) -> str:
    if ch == "'":
        return "'\\''"
    if ch == "\\":
        return "'\\\\'"
    return "'%s'" % ch


def main() -> int:
    lines = []
    w = lines.append

    w("/* GENERATED by python/scripts/gen_tm1637_corpus_header.py — DO NOT EDIT.")
    w(" *")
    w(" * TM1637 backend parity corpus.  The ORACLE is the RASTER seven-segment")
    w(" * widget (python/composeio/render/widgets/seven_segment.py), so what is")
    w(" * asserted is that the tube and the panel agree about what a character")
    w(" * MEANS and about how a value is justified — the checkable content of")
    w(" * [CXC-VISION-SEMANTIC-REALIZATION].")
    w(" *")
    w(" * NOT PINNED HERE: the segment MAP (which SEG pin drives which bar).")
    w(" * That is a property of the breakout PCB and needs eyes on a lit tube.")
    w(" * The cases below carry the a..g LETTER sets precisely so that a map")
    w(" * correction never requires regenerating this file.")
    w(" */")
    w("#ifndef TM1637_CORPUS_GENERATED_H")
    w("#define TM1637_CORPUS_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("")

    # ---- layer 1: character -> lit segment letters ----------------------
    w("/* Layer 1 — SEMANTICS: character -> lit subset of {a..g}.")
    w(" * Oracle: seven_segment.lit_segments(). */")
    w("struct Tm1637GlyphCase {")
    w("    char        ch;")
    w("    const char* segs;   /* sorted a..g letters, '' = blank */")
    w("};")
    w("static const Tm1637GlyphCase kTm1637GlyphCases[] = {")
    for ch in CHAR_CASES:
        src = PLACEHOLDER.get(ch, ch)
        segs = lit_segments(src)
        ordered = "".join(s for s in SEGMENT_ORDER if s in segs)
        note = ""
        if ch in PLACEHOLDER:
            note = "   /* ASCII stand-in for U+00B0 DEGREE SIGN */"
        w("    { %-6s, \"%s\" },%s" % (c_escape(ch), ordered, note))
    w("};")
    w("static const int kTm1637GlyphCaseCount =")
    w("    (int)(sizeof(kTm1637GlyphCases) / sizeof(kTm1637GlyphCases[0]));")
    w("")

    # ---- layer 2: justification ----------------------------------------
    w("/* Layer 2 — JUSTIFICATION: (value, digits) -> displayed cells.")
    w(" * Oracle: SevenSegmentDisplay._display_value().  Right-justified,")
    w(" * blank-padded, truncated to the RIGHTMOST cells. */")
    w("struct Tm1637JustifyCase {")
    w("    const char* value;")
    w("    int         digits;")
    w("    const char* shown;  /* exactly `digits` characters */")
    w("};")
    w("static const Tm1637JustifyCase kTm1637JustifyCases[] = {")
    for value, digits in JUSTIFY_CASES:
        widget = SevenSegmentDisplay("corpus", value=value, digits=digits)
        shown = widget._display_value()
        assert len(shown) == digits, (value, digits, shown)
        w("    { \"%s\", %d, \"%s\" }," % (value, digits, shown))
    w("};")
    w("static const int kTm1637JustifyCaseCount =")
    w("    (int)(sizeof(kTm1637JustifyCases) / sizeof(kTm1637JustifyCases[0]));")
    w("")
    w("#endif /* TM1637_CORPUS_GENERATED_H */")

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s (%d glyph cases, %d justify cases)"
          % (OUT, len(CHAR_CASES), len(JUSTIFY_CASES)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
