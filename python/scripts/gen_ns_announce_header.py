#!/usr/bin/env python3
"""
gen_ns_announce_header.py — the WELL-KNOWN ANNOUNCEMENT ROOT, baked for the
firmware parity test.  [PLAN G1/G2] of
docs/PLAN-fleet-baseline-and-bus-native.md.

`python/composeio/ns_announce.py` is what the CAN<->MQTT bridge learns with;
`cyd/src/ns_announce.h` is what a board announces with.  They must agree on
THREE things or a board announces into a void with no error anywhere:

  1. the ROOT'S HASH.  0x31AE is not "the hash of a string", it is the number
     every already-flashed node and every deployed bridge already transmit and
     listen on.  If one side renames the namespace, the other side hears
     nothing — a fleet-wide silence with no failure to report.
  2. the PAYLOAD BYTES for a given name list, exactly.  Two implementations of
     a serializer is the [BP-TYPE-CODES] shape; here a stray separator or a
     trailing NUL changes the CRC-16 and the receiver DISCARDS the transfer,
     which looks from the board's side like a board that announced fine.
  3. WHICH NAMES ARE REFUSED.  A validator that is stricter on one side than
     the other means a namespace the board happily announces is silently
     dropped by the bridge — the confidently-incomplete census this whole
     workstream exists to remove, reintroduced one layer down.

So all three are baked here and asserted by cyd/src/announce_selftest.cpp
(env:native_announce), in BOTH directions.

REGENERATE after any change to ns_announce.py or cyd/src/ns_announce.h:
    python3 python/scripts/gen_ns_announce_header.py
    pio run -e native_announce -d cyd && .pio/build/native_announce/program
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "python"))

from composeio import ns_announce as na          # noqa: E402
from composeio.config_chunk import (             # noqa: E402
    CAN_CONTENT_BYTES, chunk_config, content_hash,
)

OUT = os.path.join(REPO, "cyd", "test", "ns_announce_generated.h")


#: Name lists the C++ builder must reproduce byte for byte.  Chosen for the
#: BOUNDARIES, not for realism: one name (no separator at all), the real
#: six-namespace baseline board, and a duplicate (which must collapse, not
#: repeat — an announcement is a SET).
PAYLOAD_CASES: list[tuple[str, list[str]]] = [
    ("single name, no separator", ["_device/hosyond-080739/heartbeat"]),
    ("the baseline board's six", [
        "_device/hosyond-080739/heartbeat",
        "_device/hosyond-080739/build",
        "_device/hosyond-080739/transport",
        "_device/hosyond-080739/scene",
        "_device/hosyond-080739/health",
        "_device/hosyond-080739/announce",
    ]),
    ("a non-_device namespace announces too", ["throttle/left", "shields"]),
    ("duplicates collapse", ["a/b", "a/b", "c/d"]),
    ("the longest legal name", ["_" + "x" * (na.MAX_NAME_BYTES - 1)]),
]

#: Names that MUST be refused, and by both tiers.  Every one of these, accepted,
#: becomes a namespace on a shared segment that nobody wrote.
REFUSAL_CASES: list[tuple[str, str]] = [
    ("", "empty"),
    ("has a space", "whitespace"),
    ("tab\there", "control byte"),
    ("new\nline", "the separator itself"),
    ("/leading-slash", "must start with a letter, digit or _"),
    ("-leading-dash", "must start with a letter, digit or _"),
    ("bad#hash", "an illegal character"),
    ("x" * (na.MAX_NAME_BYTES + 1), "one byte over the ceiling"),
]

#: Names that must be ACCEPTED — the negative control for the refusals above. A
#: validator that refused everything would pass a refusal-only corpus.
ACCEPT_CASES = [
    "_device/hosyond-080739/heartbeat",
    "throttle/left",
    "a",
    "_",
    "0leading-digit",
    "dots.and-dashes_and:colons@and+plus",
    "x" * na.MAX_NAME_BYTES,
]


def _c_bytes(b: bytes) -> str:
    return ", ".join(f"0x{x:02X}" for x in b)


def _c_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f"\\x{ord(ch):02x}")
    return '"' + "".join(out) + '"'


def render() -> str:
    L: list[str] = []
    w = L.append
    w("/* GENERATED by python/scripts/gen_ns_announce_header.py — DO NOT EDIT.")
    w(" *")
    w(" * The WELL-KNOWN ANNOUNCEMENT ROOT, baked from")
    w(" * python/composeio/ns_announce.py so cyd/src/ns_announce.h can be")
    w(" * checked against it rather than merely against itself.  A C++ round")
    w(" * trip proves self-consistency and would pass with the separator")
    w(" * wrong, the ceiling off by one, or the root renamed.")
    w(" */")
    w("#ifndef NS_ANNOUNCE_GENERATED_H")
    w("#define NS_ANNOUNCE_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("#include <cstddef>")
    w("")
    w("/* ---- the root ------------------------------------------------ */")
    w(f"static const char* const kPyNsAnnounce = {_c_str(na.NS_ANNOUNCE)};")
    w(f"static const uint16_t kPyNsAnnounceHash = 0x{na.NS_ANNOUNCE_HASH:04X};")
    w(f"static const char* const kPyNsAnnouncePoll = {_c_str(na.NS_ANNOUNCE_POLL)};")
    w(f"static const uint16_t kPyNsAnnouncePollHash = "
      f"0x{na.NS_ANNOUNCE_POLL_HASH:04X};")
    w(f"static const size_t kPyNsMaxNameBytes = {na.MAX_NAME_BYTES};")
    w(f"static const size_t kPyNsMaxNames = {na.MAX_NAMES};")
    w(f"static const char kPyNsSep = '\\n';")
    w("")
    w("/* ---- payload corpus ------------------------------------------- */")
    w("struct PyNsPayloadCase {")
    w("    const char* label;")
    w("    const char* const* names;")
    w("    size_t name_count;")
    w("    const uint8_t* payload;")
    w("    size_t payload_len;")
    w("    uint16_t crc;")
    w("    size_t can_frames;   /* header + data, at 6 content bytes */")
    w("    const uint8_t* frames;      /* every frame, concatenated */")
    w("    const uint8_t* frame_lens;  /* and each one's length */")
    w("};")
    w("")
    for i, (label, names) in enumerate(PAYLOAD_CASES):
        payload = na.encode_names(names)
        frames = chunk_config(payload, CAN_CONTENT_BYTES)
        w(f"static const char* const kPyNsNames{i}[] = {{"
          + ", ".join(_c_str(n) for n in names) + "};")
        w(f"static const uint8_t kPyNsPayload{i}[] = {{{_c_bytes(payload)}}};")
        # EVERY FRAME, flattened, so the firmware's cursor arithmetic is checked
        # frame by frame rather than only via the payload it happens to produce.
        # An off-by-one on `seq` gives frames that reassemble to the right
        # LENGTH and the wrong CRC — a failure the sender cannot see.
        flat = b"".join(frames)
        w(f"static const uint8_t kPyNsFrames{i}[] = {{{_c_bytes(flat)}}};")
        w("static const uint8_t kPyNsFrameLens%d[] = {%s};"
          % (i, ", ".join(str(len(f)) for f in frames)))
        w(f"/* {label} */")
        w("")
    w("static const PyNsPayloadCase kPyNsPayloadCases[] = {")
    for i, (label, names) in enumerate(PAYLOAD_CASES):
        payload = na.encode_names(names)
        frames = chunk_config(payload, CAN_CONTENT_BYTES)
        w(f"    {{{_c_str(label)}, kPyNsNames{i}, {len(names)}, "
          f"kPyNsPayload{i}, {len(payload)}, 0x{content_hash(payload):04X}, "
          f"{len(frames)}, kPyNsFrames{i}, kPyNsFrameLens{i}}},")
    w("};")
    w(f"static const int kPyNsPayloadCaseCount = {len(PAYLOAD_CASES)};")
    w("")
    w("/* ---- names that MUST be refused, by both tiers ---------------- */")
    w("struct PyNsNameCase { const char* name; const char* why; };")
    w("static const PyNsNameCase kPyNsRefused[] = {")
    for name, why in REFUSAL_CASES:
        assert na.validate_name(name) is not None, \
            f"the Python validator ACCEPTS {name!r}; the corpus is wrong"
        w(f"    {{{_c_str(name)}, {_c_str(why)}}},")
    w("};")
    w(f"static const int kPyNsRefusedCount = {len(REFUSAL_CASES)};")
    w("")
    w("static const char* const kPyNsAccepted[] = {")
    for name in ACCEPT_CASES:
        assert na.validate_name(name) is None, \
            f"the Python validator REFUSES {name!r}; the corpus is wrong"
        w(f"    {_c_str(name)},")
    w("};")
    w(f"static const int kPyNsAcceptedCount = {len(ACCEPT_CASES)};")
    w("")
    w("#endif /* NS_ANNOUNCE_GENERATED_H */")
    w("")
    return "\n".join(L)


def main() -> int:
    text = render()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d payload cases, %d refusals, %d acceptances)"
          % (OUT, len(PAYLOAD_CASES), len(REFUSAL_CASES), len(ACCEPT_CASES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
