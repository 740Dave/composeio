#!/usr/bin/env python3
"""
gen_wire_codes_header.py — THE ONE TABLE, baked for the firmware parity test.
[SPEC:CIO-BUS-PROTOCOL] [BP-TYPE-CODES]

`MESSAGE_TYPE_WIRE_CODES` in python/composeio/transport.py allocates the 4-bit
message-type code that EVERY framed substrate carries. It is one table because
the per-transport copies drifted — transport_uart had 8 of 10 entries,
transport_can had 2, services/can_mqtt_bridge had 5, and all three ended in
`.get(msg.type, 0)`, so an unlisted type was silently re-labelled STATE on the
wire. An `ack` came back from a UART round-trip as a spurious state change.

The firmware needs the same table in C++ (cyd/src/bus_wire_codes.h). Two copies
of a table is exactly the shape that produced the defect — so this script bakes
the PYTHON table into a header, and cyd/src/wire_codes_selftest.cpp
(env:native_wire_codes) compares it against the C++ one member-for-member in
BOTH directions. Drift is then a FAILING TEST rather than a mystery on a wire.

The scope table (transport_uart._SCOPE_TO_BITS) rides along for the same reason.

Same corpus idiom as gen_dsl_corpus_header.py / gen_wrap_corpus_header.py: no
JSON parser and no filesystem on the MCU.

REGENERATE after any change to MessageType / MESSAGE_TYPE_WIRE_CODES:
    python3 python/scripts/gen_wire_codes_header.py
(python/tests/test_wire_codes_firmware_parity.py fails if you forget.)
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "python"))

from composeio.transport import (  # noqa: E402
    DEFAULT_PRIORITY,
    MESSAGE_TYPE_PRIORITY,
    MESSAGE_TYPE_WIRE_CODES,
    MessageType,
    NAMESPACE_PRIORITY_RULES,
    PRIORITY_BITS,
    WIRE_TYPE_CODE_BITS,
)
from composeio.transport_uart import _SCOPE_TO_BITS  # noqa: E402

OUT = os.path.join(REPO, "cyd", "test", "wire_codes_generated.h")


def render() -> str:
    types = sorted(MESSAGE_TYPE_WIRE_CODES.items(), key=lambda kv: kv[1])
    scopes = sorted(_SCOPE_TO_BITS.items(), key=lambda kv: kv[1])

    L: list[str] = []
    w = L.append
    w("/*")
    w(" * wire_codes_generated.h — AUTO-GENERATED. DO NOT HAND-EDIT.")
    w(" *")
    w(" * Generated by python/scripts/gen_wire_codes_header.py from")
    w(" * composeio.transport.MESSAGE_TYPE_WIRE_CODES (THE ONE TABLE,")
    w(" * [BP-TYPE-CODES]) and composeio.transport_uart._SCOPE_TO_BITS.")
    w(" *")
    w(" * This is the PYTHON side of the parity check. The firmware's own")
    w(" * table is cyd/src/bus_wire_codes.h; cyd/src/wire_codes_selftest.cpp")
    w(" * (env:native_wire_codes) asserts the two agree member-for-member in")
    w(" * BOTH directions, so a type added on one tier and forgotten on the")
    w(" * other FAILS A TEST instead of silently arriving as a STATE.")
    w(" *")
    w(f" * {len(types)} message types, {len(scopes)} scopes.")
    w(" */")
    w("")
    w("#ifndef WIRE_CODES_GENERATED_H")
    w("#define WIRE_CODES_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("")
    w("struct PyWireCode { const char* name; uint8_t code; };")
    w("")
    w("static const PyWireCode kPyWireCodes[] = {")
    for t, code in types:
        w('    { "%s", %d },' % (t.value, code))
    w("};")
    w("static const int kPyWireCodeCount = %d;" % len(types))
    w("")
    w("/* Width of the type field on every binary transport"
      " (transport.WIRE_TYPE_CODE_BITS). */")
    w("static const int kPyWireTypeCodeBits = %d;" % WIRE_TYPE_CODE_BITS)
    w("")
    w("/* Every member of composeio.transport.MessageType, in DECLARATION")
    w(" * order — so the harness can also prove the C++ enum has no member")
    w(" * the table forgot (Python enforces exactly that with a test). */")
    w("static const char* const kPyMessageTypeNames[] = {")
    for m in MessageType:
        w('    "%s",' % m.value)
    w("};")
    w("static const int kPyMessageTypeCount = %d;" % len(list(MessageType)))
    w("")
    w("struct PyScopeCode { const char* name; uint8_t bits; };")
    w("")
    w("static const PyScopeCode kPyScopeCodes[] = {")
    for name, bits in scopes:
        w('    { "%s", %d },' % (name, bits))
    w("};")
    w("static const int kPyScopeCodeCount = %d;" % len(scopes))
    w("")
    w("/* ---- arbitration priority [BP-WIRE-PRIORITY] ---- */")
    w("/* The TABLES, so the firmware's copy cannot silently gain or lose an")
    w(" * entry. The evaluated ANSWERS — which is where a matcher port goes")
    w(" * wrong — are pinned separately by the can-id corpus, which carries a")
    w(" * Python-computed tier for every (namespace, type) case it bakes. */")
    w("static const int kPyPriorityBits = %d;" % PRIORITY_BITS)
    w("static const uint8_t kPyDefaultPriority = %d;" % DEFAULT_PRIORITY)
    w("")
    w("struct PyTypePriority { const char* name; uint8_t tier; };")
    w("static const PyTypePriority kPyTypePriorities[] = {")
    for t, tier in sorted(MESSAGE_TYPE_PRIORITY.items(),
                          key=lambda kv: (kv[1], kv[0].value)):
        w('    { "%s", %d },' % (t.value, tier))
    w("};")
    w("static const int kPyTypePriorityCount = %d;" % len(MESSAGE_TYPE_PRIORITY))
    w("")
    w("/* ORDERED — first match wins, so the ORDER is part of the data. A")
    w(" * pattern ending in '/' matches by prefix; anything else is exact. */")
    w("struct PyNsPriorityRule { const char* pattern; uint8_t tier; };")
    w("static const PyNsPriorityRule kPyNsPriorityRules[] = {")
    for pattern, tier in NAMESPACE_PRIORITY_RULES:
        w('    { "%s", %d },' % (pattern, tier))
    w("};")
    w("static const int kPyNsPriorityRuleCount = %d;"
      % len(NAMESPACE_PRIORITY_RULES))
    w("")
    w("#endif /* WIRE_CODES_GENERATED_H */")
    w("")
    return "\n".join(L)


def main() -> int:
    text = render()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d types)" % (OUT, len(MESSAGE_TYPE_WIRE_CODES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
