#!/usr/bin/env python3
"""
gen_can_id_corpus_header.py — [BP-CAN-ID] v2 arbitration-id PARITY corpus.

The firmware's CAN binding (cyd/src/bus_can.cpp) has no hardware attached, so
the only thing that can be checked today is the part that is pure arithmetic —
the 29-bit extended id. That is also the part that can be wrong INVISIBLY: a
board with a mis-shifted namespace field builds, boots, logs "started", and
transmits frames no peer will ever match, and nothing says so until a wire
exists and somebody wonders why two nodes cannot hear each other.

THE ORACLE IS `services/can_mqtt_bridge.bridge.can_id_from_message`, which is
the process with hardware on the other end.

    29-bit extended id:  prio(3) | type(4) | ns_id(16) | src(4) | scope(2)

V2 ALSO ENDS [BP-CAN-ID-DIVERGENCE]. Until 2026-08-13 the bridge and the
firmware spoke `ns_hash(16)|type(4)|src(9)` while `transport_can.py` spoke
`type(4)|scope(2)|ns(16)|seq(7)` — two layouts in one repo that disagreed about
what arbitration is FOR and could not share a physical segment. The bridge now
imports its encoder FROM transport_can, so "the oracle" and "the Python
transport" are the same arithmetic by construction rather than by agreement,
and this corpus pins the C++ against it.

ALL 29 BITS ARE COMPARED NOW. The v1 corpus masked the source field out and
compared 20 of 29 bits, because the two sides were KNOWN to disagree there (the
bridge used CPython's salted `hash()`, which differs between two runs of the
same process) and the test was built not to notice. With `src` an allocated node
id both sides can name, there is nothing left to mask.

THE CORPUS ALSO PINS THE PRIORITY TIER for every (namespace, type) pair, so the
firmware's `bus_priority_for()` is checked against Python's `priority_for()`
including the DEFAULT and the prefix matcher — not just the tables, which two
implementations can agree on while their matchers disagree.

REGENERATE after any change to the id layout or the priority rules:
    python3 python/scripts/gen_can_id_corpus_header.py
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "python"))
sys.path.insert(0, REPO)

#: The node id the corpus is baked at. NOT 0: a corpus generated entirely at
#: src=0 cannot tell a correct src field from one that is missing, which is the
#: shape of self-confirming evidence this repo keeps paying for. 5 has bits set
#: in both halves of the 4-bit field. Set BEFORE the bridge is imported — it
#: reads CAN_BRIDGE_NODE_ID once, at import, which is what a service does.
CORPUS_NODE_ID = 5
os.environ["CAN_BRIDGE_NODE_ID"] = str(CORPUS_NODE_ID)

from composeio.config import namespace_hash          # noqa: E402
from composeio.transport import (                    # noqa: E402
    BusMessage, MessageType, priority_for, wire_code_for_type,
)
from services.can_mqtt_bridge.bridge import (        # noqa: E402
    CAN_NODE_ID, can_id_from_message,
)

assert CAN_NODE_ID == CORPUS_NODE_ID, (
    f"the bridge came up as node {CAN_NODE_ID}, not {CORPUS_NODE_ID} — the "
    f"corpus would bake a src field nobody asked for")

OUT = os.path.join(REPO, "cyd", "test", "can_id_corpus_generated.h")

#: Scope is baked per case, cycling all four, so a decoder that dropped the
#: field would have to be wrong on three quarters of the corpus to pass.
SCOPES = ["local", "global", "remote", "auto"]

# Namespaces chosen so the 16-bit hash spans the field: one with the high bit
# set, one with it clear, the `_device/` control shapes the config path uses,
# and the live throttle namespaces a real segment already carries. Since v2,
# ALSO chosen to exercise every priority rule branch — an exact-match rule
# (`alert_status`), a prefix rule (`throttle/`, `_app/`), and several that fall
# through to the DEFAULT tier (`sys/cpu`, `dradis/contacts`, `_device/...`).
NAMESPACES = [
    "throttle/left",
    "throttle/right",
    "sys/cpu",
    "game/ftl_ready",
    "_device/hosyond-080739/config",
    "_device/hosyond-080739/status",
    "_device/restart",
    "dradis/contacts",
    "alert_status",
    "shields",
    "_app/console/bbox",
]

# EVERY allocated type (0..9). A binding that cannot carry all ten is
# non-conformant, and eight of ten used to arrive as STATE on this substrate.
TYPES = list(MessageType)


def main() -> int:
    out = []
    w = out.append
    w("/* GENERATED by python/scripts/gen_can_id_corpus_header.py — DO NOT EDIT.")
    w(" * Oracle: services/can_mqtt_bridge.bridge.can_id_from_message")
    w(" * ([BP-CAN-ID] v2: prio(3)|type(4)|ns_id(16)|src(4)|scope(2)).")
    w(" * Consumed by cyd/src/bus_can_id_selftest.cpp (env:native_can_id).")
    w(" */")
    w("#ifndef CAN_ID_CORPUS_GENERATED_H")
    w("#define CAN_ID_CORPUS_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("")
    w(f"static const uint8_t kCanCorpusNodeIdPy = {CORPUS_NODE_ID};")
    w("")
    w("struct CanIdCase {")
    w("    const char* ns;")
    w("    uint16_t ns_hash;")
    w("    const char* type_name;")
    w("    uint8_t type_code;")
    w("    uint8_t prio;           /* [BP-WIRE-PRIORITY] tier Python assigned */")
    w("    const char* scope_name;")
    w("    uint32_t id;            /* the WHOLE 29-bit id — nothing masked */")
    w("};")
    w("static const CanIdCase kCanIdCases[] = {")
    n = 0
    for ns in NAMESPACES:
        for i, t in enumerate(TYPES):
            scope = SCOPES[(n + i) % len(SCOPES)]
            msg = BusMessage(namespace=ns, type=t, value=1, source="probe",
                             scope=scope)
            arb = can_id_from_message(msg)
            assert arb <= 0x1FFFFFFF, f"id {arb:#x} exceeds 29 bits"
            # `wire_code_for_type`, NEVER the enumeration index — the two
            # coincide today and that coincidence is exactly what the type
            # table exists to stop anyone relying on.
            w(f'    {{ "{ns}", 0x{namespace_hash(ns):04X}, "{t.value}", '
              f'{wire_code_for_type(t)}, {priority_for(ns, t)}, "{scope}", '
              f'0x{arb:08X} }},')
            n += 1
    w("};")
    w(f"static const int kCanIdCaseCount = {n};")
    w("")
    w("#endif /* CAN_ID_CORPUS_GENERATED_H */")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {n} cases "
          f"({len(NAMESPACES)} namespaces x {len(TYPES)} message types)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
