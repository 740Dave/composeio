#!/usr/bin/env python3
"""
gen_dsl_corpus_header.py — corpus -> C++ header generator
([SPEC:CXC-DSL] [CXC-DSL-CROSSPLAT], Pass 2b).

Reads the language-agnostic conformance corpus
    python/composeio/render/engine/dsl_conformance/dsl_corpus.json
and emits
    cyd/test/dsl_corpus_generated.h
— a self-contained C++ header holding all cases as static const data
(expr source, ns/vars tables, dt/t as exact IEEE-754 bits, expected
value as exact bits / bool / string, or expected error kind).

This lets BOTH the host conformance harness AND the on-device ESP32
runner consume the corpus with NO JSON parser and NO filesystem on the
MCU: the cases live in flash (.rodata).

Re-run this script after ANY corpus change:

    python3 python/scripts/gen_dsl_corpus_header.py

The emitted header records the source corpus case count; the C++
harness prints it, so a stale header is visible as a count mismatch
against the Python runner's output.
"""

from __future__ import annotations

import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))          # composeio/
CORPUS = os.path.join(REPO, "python", "composeio", "render", "engine",
                      "dsl_conformance", "dsl_corpus.json")
OUT = os.path.join(REPO, "cyd", "test", "dsl_corpus_generated.h")

# expected-kind codes (must match dsl_selftest.cpp)
EXPECT_NUMBER, EXPECT_BOOL, EXPECT_STRING = 0, 1, 2
EXPECT_PARSE_ERROR, EXPECT_EVAL_ERROR = 3, 4


def dbits(x: float) -> int:
    """Big-endian IEEE-754 binary64 bits of *x* as an int."""
    return struct.unpack(">Q", struct.pack(">d", float(x)))[0]


def cstr(s: str) -> str:
    """C string literal (ASCII-safe escaping)."""
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % o)
    out.append('"')
    return "".join(out)


def value_init(v) -> str:
    """DslCorpusValue initializer for a raw JSON ns/var value.

    kind: 0 = number (bits), 1 = bool, 2 = string.
    NOTE: bool check MUST precede number (Python bool is an int)."""
    if isinstance(v, bool):
        return "{1, 0ULL, %d, nullptr}" % (1 if v else 0)
    if isinstance(v, (int, float)):
        return "{0, 0x%016XULL, 0, nullptr}" % dbits(v)
    if isinstance(v, str):
        return "{2, 0ULL, 0, %s}" % cstr(v)
    raise SystemExit(f"unsupported raw value type {type(v)!r}: {v!r}")


def main() -> int:
    with open(CORPUS, encoding="utf-8") as f:
        corpus = json.load(f)
    if corpus.get("format") != "composeux-dsl-conformance-v1":
        raise SystemExit("unknown corpus format")
    cases = corpus["cases"]
    assert len(cases) == corpus["case_count"], "corpus count mismatch"

    lines = []
    w = lines.append
    w("/*")
    w(" * dsl_corpus_generated.h — AUTO-GENERATED. DO NOT HAND-EDIT.")
    w(" *")
    w(" * Generated by python/scripts/gen_dsl_corpus_header.py from")
    w(" * python/composeio/render/engine/dsl_conformance/dsl_corpus.json")
    w(f" * (format {corpus['format']}, {len(cases)} cases).")
    w(" *")
    w(" * REGENERATE after any corpus change:")
    w(" *   python3 python/scripts/gen_dsl_corpus_header.py")
    w(" *")
    w(" * All data is static const -> lives in flash (.rodata) on the")
    w(" * ESP32; no JSON parser and no filesystem needed on the MCU.")
    w(" */")
    w("")
    w("#ifndef DSL_CORPUS_GENERATED_H")
    w("#define DSL_CORPUS_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("")
    w("/* Raw ns/var value: kind 0 = number (IEEE-754 bits), 1 = bool,")
    w(" * 2 = string. */")
    w("struct DslCorpusValue {")
    w("    uint8_t kind;")
    w("    uint64_t bits;")
    w("    uint8_t b;")
    w("    const char* s;")
    w("};")
    w("")
    w("struct DslCorpusEntry {")
    w("    const char* name;")
    w("    DslCorpusValue value;")
    w("};")
    w("")
    w("/* expect: 0 = number (expect_bits authoritative), 1 = bool,")
    w(" * 2 = string, 3 = parse_error, 4 = eval_error. */")
    w("struct DslCorpusCase {")
    w("    const char* id;")
    w("    const char* group;")
    w("    const char* expr;")
    w("    const DslCorpusEntry* ns;")
    w("    uint8_t ns_count;")
    w("    const DslCorpusEntry* vars;")
    w("    uint8_t var_count;")
    w("    uint64_t dt_bits;   /* IEEE-754 bits of dt */")
    w("    uint64_t t_bits;    /* IEEE-754 bits of t  */")
    w("    uint8_t expect;")
    w("    uint64_t expect_bits;")
    w("    uint8_t expect_bool;")
    w("    const char* expect_str;")
    w("};")
    w("")

    # per-case ns/vars tables
    for i, case in enumerate(cases):
        for field in ("ns", "vars"):
            entries = case.get(field)
            if entries:
                w(f"static const DslCorpusEntry k_case{i}_{field}[] = {{")
                for name, raw in entries.items():
                    w(f"    {{{cstr(name)}, {value_init(raw)}}},")
                w("};")
    w("")
    w("static const DslCorpusCase kDslCorpusCases[] = {")
    for i, case in enumerate(cases):
        ns = case.get("ns") or {}
        vs = case.get("vars") or {}
        ns_ref = f"k_case{i}_ns" if ns else "nullptr"
        vs_ref = f"k_case{i}_vars" if vs else "nullptr"
        dt_bits = dbits(case.get("dt", 0.0))
        t_bits = dbits(case.get("t", 0.0))
        if "error" in case:
            kind = {"parse": EXPECT_PARSE_ERROR,
                    "eval": EXPECT_EVAL_ERROR}[case["error"]]
            ebits, ebool, estr = 0, 0, "nullptr"
        else:
            exp = case["expected"]
            if exp["type"] == "number":
                kind = EXPECT_NUMBER
                ebits = int(exp["hex"], 16)
                ebool, estr = 0, "nullptr"
            elif exp["type"] == "bool":
                kind = EXPECT_BOOL
                ebits, ebool, estr = 0, (1 if exp["value"] else 0), "nullptr"
            elif exp["type"] == "string":
                kind = EXPECT_STRING
                ebits, ebool, estr = 0, 0, cstr(exp["value"])
            else:
                raise SystemExit(f"unknown expected type in {case['id']}")
        w("    {%s, %s, %s,\n"
          "     %s, %d, %s, %d,\n"
          "     0x%016XULL, 0x%016XULL,\n"
          "     %d, 0x%016XULL, %d, %s},"
          % (cstr(case["id"]), cstr(case["group"]), cstr(case["expr"]),
             ns_ref, len(ns), vs_ref, len(vs),
             dt_bits, t_bits, kind, ebits, ebool, estr))
    w("};")
    w("")
    w(f"static const int kDslCorpusCaseCount = {len(cases)};")
    w("")
    w("#endif /* DSL_CORPUS_GENERATED_H */")
    w("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(cases)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
