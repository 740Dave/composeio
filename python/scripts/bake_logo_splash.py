#!/usr/bin/env python3
"""
ComposePlatform logo -> boot-splash CI16 header baker (embedded tier).

The firmware boot splash renders BEFORE any network dependency (it proves
the panel), so the logo cannot be fetched from bus_storage like a sprite —
it must be compiled into the binary.  This bakes the tracked logo asset
(cyd/assets/compose_logo_1024.png) into the CYD/Qualia drawable CI16 raw
format (RGB565, no alpha — composited over the splash background color,
exactly the [CXC-R-C18] sprite-baker degradation) and emits a C header
holding the bytes as a static array, plus width/height, ready to
decode_image()/draw_image() on-device.

One header per display env (the band-tier CYD has a 120 KB decode budget;
the Qualia has PSRAM), sized so the logo is the boot hero.

Usage (regenerates both tracked headers from the tracked source):
    cd ~/Dropbox/Maker/composeio/python
    python scripts/bake_logo_splash.py

Reproducible: the source PNG and the generated headers are both committed;
re-running this must reproduce the headers byte-for-byte.
"""

from __future__ import annotations

import os
import struct
import sys

from PIL import Image

_here = os.path.dirname(os.path.abspath(__file__))
_repo = os.path.abspath(os.path.join(_here, os.pardir, os.pardir))

SRC_PNG = os.path.join(_repo, "cyd", "assets", "compose_resources/compose_logo_1024.png")
OUT_DIR = os.path.join(_repo, "cyd", "src", "gen")

# (symbol, macro-prefix, side px, background RRGGBB) — one hero per env.
#   qualia : 720x720 round, PSRAM decode budget -> a large hero (400px)
#   cyd    : 240x320 band tier, 120 KB decode budget -> 160px (51 KB)
TARGETS = [
    ("compose_resources/compose_logo_splash_qualia", "COMPOSE_LOGO_QUALIA", 400, (0x10, 0x12, 0x1C)),
    ("compose_resources/compose_logo_splash_cyd",    "COMPOSE_LOGO_CYD",    160, (0x1E, 0x1E, 0x2E)),
]


def bake_ci16(side: int, bg: tuple) -> bytes:
    """Contain-fit the logo into side x side over bg, emit CI16 (RGB565 LE)."""
    src = Image.open(SRC_PNG).convert("RGBA")
    fit = src.copy()
    fit.thumbnail((side, side), Image.LANCZOS)          # preserve aspect
    canvas = Image.new("RGBA", (side, side), (*bg, 255))
    ox = (side - fit.width) // 2
    oy = (side - fit.height) // 2
    canvas.alpha_composite(fit, (ox, oy))
    rgb = canvas.convert("RGB")
    px = rgb.load()

    data = bytearray(b"CI16")
    data += struct.pack("<HH", side, side)
    for y in range(side):
        for x in range(side):
            r, g, b = px[x, y]
            c = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            data += struct.pack("<H", c)
    return bytes(data)


def emit_header(sym: str, macro: str, side: int, data: bytes) -> str:
    lines = [
        "/* GENERATED by python/scripts/bake_logo_splash.py — do not edit.",
        " * ComposePlatform boot-splash logo, baked CI16 (RGB565, no alpha,",
        " * composited over the splash background).  Source of truth:",
        " * cyd/assets/compose_logo_1024.png.  Re-run the baker to regenerate.",
        " */",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
        f"#define {macro}_W {side}",
        f"#define {macro}_H {side}",
        "",
        f"static const uint8_t {sym}[] = {{",
    ]
    row = []
    for b in data:
        row.append(f"0x{b:02X},")
        if len(row) == 16:
            lines.append("    " + "".join(row))
            row = []
    if row:
        lines.append("    " + "".join(row))
    lines.append("};")
    lines.append(f"static const size_t {sym}_len = sizeof({sym});")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    if not os.path.exists(SRC_PNG):
        sys.exit(f"missing tracked source asset: {SRC_PNG}")
    os.makedirs(OUT_DIR, exist_ok=True)
    for sym, macro, side, bg in TARGETS:
        data = bake_ci16(side, bg)
        hdr = emit_header(sym, macro, side, data)
        path = os.path.join(OUT_DIR, sym + ".h")
        with open(path, "w") as f:
            f.write(hdr)
        decoded = side * side * 2
        print(f"{sym}: {side}x{side} -> {path}  "
              f"(flash {len(data) + 8} B, on-device decode {decoded} B)")


if __name__ == "__main__":
    main()
