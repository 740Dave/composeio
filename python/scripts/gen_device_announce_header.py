#!/usr/bin/env python3
"""
gen_device_announce_header.py — the announcement tables + a PACKING CORPUS,
baked for the firmware parity test.  [SPEC:CXC-BOARD-HW] workstream 0.2.

`python/composeio/device_announce.py` decodes what every board publishes on
`_device/<id>/*`; `cyd/src/announce_pack.h` is the C++ implementation that
encodes it.  Two implementations of one table is exactly the shape that
produced the [BP-TYPE-CODES] defect — three forks of the message-type map, each
ending in `.get(t, 0)`, so an ACK arrived on the wire as a STATE.

So this bakes the PYTHON side into a header and cyd/src/announce_selftest.cpp
(env:native_announce) compares it against the C++ side in both directions.
Drift then FAILS A TEST instead of producing a fleet report that quietly names
the wrong firmware, the wrong substrate or a healthy-looking bus-off board.

IT SHIPS A CORPUS, NOT ONLY THE TABLES, and that distinction is the point.
Comparing two name tables proves the two files agree about spelling.  What
actually has to agree is the ARITHMETIC — the shifts, the masks, the
saturation rules.  A `health` word whose heap field is shifted 16 on one tier
and 15 on the other produces two plausible numbers and no error anywhere.  The
corpus is generated by running the PYTHON packer over boundary cases (empty,
full, saturating, every reset reason, every link state) and the C++ side must
reproduce each 32-bit word exactly.

REGENERATE after any change to device_announce.py or announce_pack.h:
    python3 python/scripts/gen_device_announce_header.py
    pio run -e native_announce -d cyd && .pio/build/native_announce/program
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "python"))

from composeio import device_announce as da  # noqa: E402

OUT = os.path.join(REPO, "cyd", "test", "device_announce_generated.h")


def _health_corpus() -> list[tuple[str, int, int, int, int]]:
    """(label, free_heap_bytes, reset_reason, link, flags).

    Chosen for the BOUNDARIES, not for realism: a packing bug that survives a
    plausible mid-range value is caught by 0, by the field maximum, and by the
    value one past it.
    """
    cases: list[tuple[str, int, int, int, int]] = [
        ("all zero", 0, 0, 0, 0),
        ("1 KB exactly", 1024, 0, 0, 0),
        ("1023 B rounds to 0 KB", 1023, 0, 0, 0),
        # The realistic band: an ESP32 with no PSRAM boots with ~50 KB free and
        # this is the value an operator will actually read.
        ("50 KB typical", 50 * 1024, 1, 1, 0x01 | 0x04 | 0x08),
        ("8 MB PSRAM board", 8 * 1024 * 1024, 1, 1, 0x0F),
        # SATURATION, both sides of the edge.  A heap field that WRAPS would
        # report a starving board as a roomy one — the exact direction of error
        # that gets ignored.
        ("heap at saturation", 0xFFFF * 1024, 0, 0, 0),
        # 4 GB - 1: the largest value esp_get_free_heap_size() can physically
        # return.  Deliberately NOT something larger: the C++ packer takes a
        # uint32_t, so a Python-only value would not compile and would be
        # testing an input the firmware cannot produce.
        ("heap past saturation", 0xFFFFFFFF, 0, 0, 0),
        ("every flag set", 12345 * 1024, 4, 4, 0xFF),
        ("reset reason max", 4096, 15, 0, 0),
        ("reset reason over max saturates", 4096, 99, 0, 0),
        ("link over max saturates", 4096, 0, 99, 0),
        # The H2 contradiction, encoded: the transport CLAIMS connected while
        # the link is down.  A fleet report has to be able to say this.
        ("claims connected, link down", 40 * 1024, 1, 4, 0x04 | 0x01),
    ]
    for code, name in sorted(da.RESET_REASONS.items()):
        cases.append((f"reset={name}", 32 * 1024, code, 1, 0x01))
    for code, name in sorted(da.LINK_HEALTH.items()):
        cases.append((f"link={name}", 32 * 1024, 1, code, 0x01))
    return cases


def _transport_corpus() -> list[tuple[int, bool]]:
    out: list[tuple[int, bool]] = []
    for code in sorted(da.TRANSPORT_CODES):
        out.append((code, False))
        out.append((code, True))
    return out


def _c_str(s: str) -> str:
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def render() -> str:
    L: list[str] = []
    w = L.append
    health = _health_corpus()
    transport = _transport_corpus()

    w("/*")
    w(" * device_announce_generated.h — AUTO-GENERATED.  DO NOT HAND-EDIT.")
    w(" *")
    w(" * Generated by python/scripts/gen_device_announce_header.py from")
    w(" * python/composeio/device_announce.py — the ORACLE for device")
    w(" * self-announcement ([SPEC:CXC-BOARD-HW] workstream 0.2).")
    w(" *")
    w(" * The firmware's own implementation is cyd/src/announce_pack.h;")
    w(" * cyd/src/announce_selftest.cpp (env:native_announce) asserts the two")
    w(" * agree on every NAME and, more importantly, on every packed WORD.")
    w(" * A shift that differs by one between the tiers produces two plausible")
    w(" * numbers and no error anywhere — which is why the corpus exists and a")
    w(" * name-table comparison alone would not be enough.")
    w(" *")
    w(f" * {len(transport)} transport cases, {len(health)} health cases.")
    w(" */")
    w("")
    w("#ifndef DEVICE_ANNOUNCE_GENERATED_H")
    w("#define DEVICE_ANNOUNCE_GENERATED_H")
    w("")
    w("#include <cstdint>")
    w("")
    w("/* ---- names ---- */")
    w("")
    w("struct PyCodeName { uint8_t code; const char* name; };")
    w("")
    w("static const PyCodeName kPyTransportCodes[] = {")
    for code, name in sorted(da.TRANSPORT_CODES.items()):
        w("    { %d, %s }," % (code, _c_str(name)))
    w("};")
    w("static const int kPyTransportCodeCount = %d;" % len(da.TRANSPORT_CODES))
    w("")
    w("static const PyCodeName kPyLinkHealth[] = {")
    for code, name in sorted(da.LINK_HEALTH.items()):
        w("    { %d, %s }," % (code, _c_str(name)))
    w("};")
    w("static const int kPyLinkHealthCount = %d;" % len(da.LINK_HEALTH))
    w("")
    w("/* ---- bit positions and masks ---- */")
    w("")
    w("static const uint8_t kPyTransportNvsBit = 0x%02X;" % da.TRANSPORT_NVS_BIT)
    w("static const uint8_t kPyTransportCodeMask = 0x%02X;"
      % da.TRANSPORT_CODE_MASK)
    w("static const int kPyHealthHeapShift = %d;" % da.HEALTH_HEAP_SHIFT)
    w("static const int kPyHealthResetShift = %d;" % da.HEALTH_RESET_SHIFT)
    w("static const int kPyHealthLinkShift = %d;" % da.HEALTH_LINK_SHIFT)
    w("")
    w("/* Flag bits, by the SHORT NAME a fleet report prints. */")
    w("static const PyCodeName kPyHealthFlags[] = {")
    for bit, name in sorted(da.HEALTH_FLAGS.items()):
        w("    { 0x%02X, %s }," % (bit, _c_str(name)))
    w("};")
    w("static const int kPyHealthFlagCount = %d;" % len(da.HEALTH_FLAGS))
    w("")
    w("/* ---- packing corpus: the PYTHON packer's output ---- */")
    w("")
    w("struct PyTransportCase { uint8_t code; int from_nvs; uint8_t packed; };")
    w("")
    w("static const PyTransportCase kPyTransportCases[] = {")
    for code, nvs in transport:
        w("    { %d, %d, 0x%02X }," % (code, 1 if nvs else 0,
                                       da.pack_transport(code, nvs)))
    w("};")
    w("static const int kPyTransportCaseCount = %d;" % len(transport))
    w("")
    w("struct PyHealthCase {")
    w("    const char* label;")
    w("    uint32_t free_heap_bytes;")
    w("    uint8_t reset_reason;")
    w("    uint8_t link;")
    w("    uint8_t flags;")
    w("    uint32_t packed;")
    w("};")
    w("")
    w("static const PyHealthCase kPyHealthCases[] = {")
    for label, heap, rr, link, flags in health:
        # The C++ side takes a uint32_t; a corpus entry outside that range
        # would not compile (and would be an input no ESP32 can produce).
        assert 0 <= heap <= 0xFFFFFFFF, f"{label}: heap out of uint32 range"
        packed = da.pack_health(heap, rr, link, flags)
        w("    { %s, %uu, %d, %d, 0x%02X, 0x%08Xu }," %
          (_c_str(label), heap, rr, link, flags, packed))
    w("};")
    w("static const int kPyHealthCaseCount = %d;" % len(health))
    w("")
    w("/* ---- hex rendering: what a 32/16-bit word looks like on the wire ---- */")
    w("")
    w("struct PyHexCase { uint32_t value; const char* hex32; };")
    w("")
    hex_vals = [0x00000000, 0x00000001, 0x0000FFFF, 0x12813962, 0xDEADBEEF,
                0xFFFFFFFF, 0xABCDEF01]
    w("static const PyHexCase kPyHex32Cases[] = {")
    for v in hex_vals:
        w("    { 0x%08Xu, %s }," % (v, _c_str("%08x" % v)))
    w("};")
    w("static const int kPyHex32CaseCount = %d;" % len(hex_vals))
    w("")
    hex16 = [0x0000, 0x0001, 0x6F62, 0xFFFF, 0x00AB]
    w("static const PyHexCase kPyHex16Cases[] = {")
    for v in hex16:
        w("    { 0x%04Xu, %s }," % (v, _c_str("%04x" % v)))
    w("};")
    w("static const int kPyHex16CaseCount = %d;" % len(hex16))
    w("")
    w("#endif /* DEVICE_ANNOUNCE_GENERATED_H */")
    w("")
    return "\n".join(L)


def main() -> int:
    text = render()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d health cases, %d transport cases)"
          % (OUT, len(_health_corpus()), len(_transport_corpus())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
