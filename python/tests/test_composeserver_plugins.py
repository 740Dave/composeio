# ---- the CLI ---------------------------------------------------------------- #
def _cli(*args):
    return subprocess.run([sys.executable, "-m", "composeio.composeserver_plugins", *args],
                          capture_output=True, text=True)


def test_cli_without_consent_exits_nonzero_and_installs_nothing(tmp_path):
    r = _cli("install", str(package_dir("v1")), "--state-root", str(tmp_path))
    print(r.stderr)
    assert r.returncode == 2 and "nothing was installed" in r.stderr
    host = CP.ComposeIOPluginHost(state_root=tmp_path)
    assert host.manager.record("hello_world") is None
    r = _cli("install", str(package_dir("v1")), "--state-root", str(tmp_path), "--consent")
    assert r.returncode == 2   # --consent without an operator is not consent


def test_cli_with_consent_records_the_operator(tmp_path):
    r = _cli("install", str(package_dir("v1")), "--state-root", str(tmp_path),
             "--consent", "--operator", "dave")
    assert r.returncode == 0, r.stderr
    host = CP.ComposeIOPluginHost(state_root=tmp_path)
    assert [x.decided_by for x in host.manager.consent.records()] == ["dave"]
    assert "runs as: inprocess" in r.stdout


