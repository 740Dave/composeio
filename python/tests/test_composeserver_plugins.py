def _server_with_host(tmp_path, level="inprocess"):
    server = ComposeServer()
    host = CP.ComposeIOPluginHost(state_root=tmp_path / "s", minimum_isolation=level,
                                  server=server, tenant_id="t1")
    return server, host


def test_tenant_manifest_domain_without_install_record_parks_and_never_imports(tmp_path):
    server, host = _server_with_host(tmp_path)
    sys.modules.pop("hello_world", None)
    res = load_tenant_manifest(server, "t1", {"plugins": [{"plugin": "hello_world"}]},
                               plugin_host=host)
    assert res.config_parked == {"hello_world": [
        "resolve:no install record for domain 'hello_world'"]}
    assert "hello_world" not in sys.modules and host.manager.record("hello_world") is None


@pytest.mark.parametrize("level", ["inprocess", "subprocess"])
def test_tenant_manifest_domain_with_an_install_record_is_enabled(tmp_path, level):
    server, host = _server_with_host(tmp_path, level)
    p = host.manager.prepare_install(package_dir("v1"))
    host.manager.install(package_dir("v1"), consented_sha256=p.manifest_sha256,
                         operator="dave", accepted=True)
    res = load_tenant_manifest(server, "t1", {"plugins": [
        {"plugin": "hello_world", "config": {"greeting": "from tenant manifest"}}]},
        plugin_host=host)
    try:
        assert res.config_parked == {}
        bus = server.tenant_bus("t1")
        from compose_plugins.conformance import wait_for
        assert wait_for(lambda: bus.get_state("plugins/hello_world/greeting")
                        == "from tenant manifest")
        status = bus.get_state("_server/plugins/hello_world/status")
        assert status["status"] == "running" and status["contract"] == "0.1"
    finally:
        host.manager.disable("hello_world")


