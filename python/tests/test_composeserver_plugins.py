def test_gate_needs_an_explicit_accept_and_an_operator(tmp_path):
    host = CP.ComposeIOPluginHost(state_root=tmp_path)
    from compose_plugins.host import ConsentRequest
    p = host.manager.prepare_install(package_dir("v1"))

    def req(op, acc):
        return ConsentRequest("install", "hello_world", "1.0.0", p.manifest_sha256,
                              p.content, op, acc)
    assert host.consent_gate(req("dave", True)).decision == "granted"
    assert host.consent_gate(req("dave", True)).decided_by == "dave"
    for op, acc in (("dave", False), (None, True), ("  ", True)):
        assert host.consent_gate(req(op, acc)).decision == "refused"


