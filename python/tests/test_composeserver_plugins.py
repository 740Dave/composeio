# ---- r18 composeio-health-tick ---------------------------------------------- #
WENT_BAD = ('    def health_reason(self):\n        import time\n'
            "        if not hasattr(self, '_t0'): self._t0 = time.time()\n"
            "        return 'went bad' if time.time() - self._t0 > 1.0 else None\n")


def _went_bad_pkg(tmp_path):
    import shutil
    dst = tmp_path / "bad"
    shutil.copytree(package_dir("v1"), dst, ignore=shutil.ignore_patterns("__pycache__"))
    p = dst / "hello_world" / "plugin.py"
    p.write_text(p.read_text().replace(
        '    def health_reason(self):\n        return "empty greeting" if self.config.greeting == "" else None\n',
        WENT_BAD))
    assert "went bad" in p.read_text()
    return dst


@pytest.mark.parametrize("level", ["inprocess", "subprocess"])
def test_composeserver_announce_tick_drives_health(tmp_path, monkeypatch, level):
    """The library's own in-process poll is switched OFF: only ComposeServer's
    per-tenant announce tick can report the plug-in turning unwell."""
    import compose_plugins.runner as runner
    monkeypatch.setattr(runner, "HEALTH_POLL_S", 3600.0)
    t = CP.conformance_target(level, tmp_path / "w")
    try:
        src = _went_bad_pkg(tmp_path)
        p = t.manager.prepare_install(src)
        t.manager.install(src, consented_sha256=p.manifest_sha256, operator="dave", accepted=True)
        t.manager.enable("hello_world")
        assert t.manager.tick in t.server._tenants[t.tenant_id].tick_hooks
        ok = conformance.wait_for(
            lambda: t.manager.status("hello_world") == "degraded(went bad)", 8)
        print(level, t.manager.status("hello_world"))
        assert ok
        st = t.bus.get_state("_server/plugins/hello_world/status")
        assert st["status"] == "degraded(went bad)"
    finally:
        t.close()


def test_tick_hook_seam_runs_hooks_and_survives_a_bad_one(tmp_path):
    server = ComposeServer()
    server.add_tenant("t", plugins=[], start=False)
    calls = []
    server.add_tick_hook("t", lambda: (_ for _ in ()).throw(RuntimeError("bad hook")))
    server.add_tick_hook("t", lambda: calls.append(1))
    tenant = server._tenants["t"]
    server._install_announce_tick(tenant)
    try:
        tenant._announce_tick(0.0)
        assert calls == [1]
    finally:
        server._remove_announce_tick(tenant)
