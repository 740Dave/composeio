def _secrets(tmp_path, operators):
    path = tmp_path / "secrets.yaml"
    path.write_text(yaml.safe_dump({"composeserver": {"plugin_manager": {"operators": operators}},
                                    "other": {"x": 1}}))
    return path


def _basic(user, token):
    import base64
    return "Basic " + base64.b64encode(f"{user}:{token}".encode()).decode()


def _env(user=None, token=None, addr="127.0.0.1", header=None):
    env = {"REMOTE_ADDR": addr}
    if header is not None:
        env["HTTP_AUTHORIZATION"] = header
    elif user is not None:
        env["HTTP_AUTHORIZATION"] = _basic(user, token)
    return env


