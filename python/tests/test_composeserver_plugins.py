def test_default_secrets_location_is_the_ruled_reference():
    assert CP.DEFAULT_SECRETS_PATH == Path(os.environ.get("COMPOSEIO_SECRETS_PATH", "~/.config/composeio/secrets.yaml"))
    assert CP.OPERATORS_KEY == ("composeserver", "plugin_manager", "operators")


def test_loopback_basic_with_the_operators_token_is_that_operator(tmp_path):
    tok, other = secrets.token_urlsafe(32), secrets.token_urlsafe(32)
    auth = CP.LoopbackTokenAuth(_secrets(tmp_path, {"dave": tok, "plumb": other}))
    assert auth(_env("dave", tok)) == "dave"
    assert auth(_env("plumb", other, addr="::1")) == "plumb"


@pytest.mark.parametrize("case", ["remote", "no-header", "wrong-token", "other-operators-token",
                                  "unknown-operator", "empty-password", "bearer", "not-base64",
                                  "no-colon"])
def test_everything_else_is_denied(tmp_path, case):
    tok, other = secrets.token_urlsafe(32), secrets.token_urlsafe(32)
    auth = CP.LoopbackTokenAuth(_secrets(tmp_path, {"dave": tok, "plumb": other}))
    import base64
    env = {"remote": _env("dave", tok, addr="mqtt-broker.local"),
           "no-header": _env(),
           "wrong-token": _env("dave", secrets.token_urlsafe(32)),
           "other-operators-token": _env("dave", other),
           "unknown-operator": _env("eve", tok),
           "empty-password": _env("dave", ""),
           "bearer": _env(header=f"Bearer {tok}"),
           "not-base64": _env(header="Basic !!!not-base64!!!"),
           "no-colon": _env(header="Basic " + base64.b64encode(f"dave{tok}".encode()).decode()),
           }[case]
    assert auth(env) is None


def test_token_is_compared_in_constant_time(tmp_path, monkeypatch):
    tok = secrets.token_urlsafe(32)
    auth = CP.LoopbackTokenAuth(_secrets(tmp_path, {"dave": tok}))
    calls = []
    real = CP.hmac.compare_digest
    monkeypatch.setattr(CP.hmac, "compare_digest",
                        lambda a, b: calls.append(1) or real(a, b))
    assert auth(_env("dave", tok)) == "dave"
    assert auth(_env("eve", tok)) is None          # unknown operator: still compared
    assert len(calls) == 2


@pytest.mark.parametrize("content", [None, {"composeserver": {}}, {"other": 1}, "not a map",
                                     {"composeserver": {"plugin_manager": {"operators": []}}}])
def test_absent_key_or_file_denies_all(tmp_path, content):
    """Until HoP provisions the key, the production hook denies everything."""
    path = tmp_path / "secrets.yaml"
    if content is not None:
        path.write_text(yaml.safe_dump(content))
    auth = CP.LoopbackTokenAuth(path)
    assert auth(_env("dave", secrets.token_urlsafe(32))) is None
    assert auth(_env()) is None


def _get(app, path, env):
    out = {}
    body = b"".join(app({"REQUEST_METHOD": "GET", "SCRIPT_NAME": "", "PATH_INFO": path,
                         "wsgi.input": io.BytesIO(), **env},
                        lambda s, h: out.update(status=s, headers=dict(h))))
    return out["status"], out["headers"], body


def test_production_hook_with_absent_key_denies_every_route_with_a_basic_challenge(tmp_path):
    host = CP.ComposeIOPluginHost(state_root=tmp_path / "s",
                                  auth_hook=CP.LoopbackTokenAuth(tmp_path / "absent.yaml"))
    app = PluginManagerApp(host.manager)
    tok = secrets.token_urlsafe(32)
    for path in ("/", "/consent", "/plugin/hello_world"):
        status, headers, body = _get(app, path, _env("dave", tok))
        assert status == "401 Unauthorized"
        assert headers["WWW-Authenticate"] == \
            'Basic realm="ComposeServer Plugin Manager", charset="UTF-8"'
        assert tok.encode() not in body and "dave" not in body.decode()


def test_browser_gets_the_native_prompt_then_the_manager_with_credentials(tmp_path):
    tok = secrets.token_urlsafe(32)
    host = CP.ComposeIOPluginHost(state_root=tmp_path / "s",
                                  auth_hook=CP.LoopbackTokenAuth(_secrets(tmp_path, {"dave": tok})))
    app = PluginManagerApp(host.manager)
    status, headers, _ = _get(app, "/", _env())
    assert status == "401 Unauthorized" and headers["WWW-Authenticate"].startswith("Basic realm=")
    status, headers, body = _get(app, "/", _env("dave", tok))
    assert status == "200 OK" and b"Plugin Manager" in body and tok.encode() not in body


def test_a_token_is_never_logged_or_echoed(tmp_path, caplog):
    tok = secrets.token_urlsafe(32)
    path = _secrets(tmp_path, {"dave": tok})
    caplog.set_level(logging.DEBUG)
    auth = CP.LoopbackTokenAuth(path)
    auth(_env("dave", tok))
    auth(_env("dave", tok + "x"))
    bad = tmp_path / "bad.yaml"
    bad.write_text(f"composeserver: [{tok}\n")
    CP.LoopbackTokenAuth(bad)(_env("dave", tok))
    assert tok not in caplog.text


